/** Per-audience View/Edit matrix (Kensium: User Defined Fields). */
export interface FieldPermissions {
  hrView: boolean
  hrEdit: boolean
  managerView: boolean
  managerEdit: boolean
  employeeView: boolean
  employeeEdit: boolean
}

export interface FieldDefinition {
  id: string
  name: string
  entity: SupportedEntity
  scope: FieldScope
  /** Owning tenant/group; 'All companies' for platform scope. */
  owner: string
  type: FieldType
  /** Configured options for single-/multi-select lists. */
  options: string[]
  /** Target entity for lookup/reference fields. */
  lookupEntity: SupportedEntity | null
  required: boolean
  /** Included on the standard form out of the box. */
  isDefault: boolean
  mask: string
  regex: string
  description: string
  /** Render sequence within its entity's form. */
  order: number
  version: number
  effectiveDate: string
  updatedBy: string
  updatedAt: string
  permissions: FieldPermissions
}

